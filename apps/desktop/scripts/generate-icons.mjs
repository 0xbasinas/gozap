#!/usr/bin/env node
// Generate every app icon from one source image.
// Usage: pnpm icons [path/to/source.svg|png]   (default: build/icon-source.svg, ideally 1024x1024)
// Writes: build/icon.png, build/icon.ico, build/icon.icns, resources/icon.png, and for the sign-in email the logo
// (../web/public/email-logo.png) and the brand colour taken from it (../api/src/brand.ts).
import { readFileSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'
import png2icons from 'png2icons'

const source = process.argv[2] ?? 'build/icon-source.svg'

const render = (size) =>
  sharp(readFileSync(source), { density: 384 })
    .resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer()

const master = await render(1024)

writeFileSync('build/icon.png', master)
writeFileSync('resources/icon.png', await render(512))

const ico = png2icons.createICO(master, png2icons.BICUBIC, 0, false, true)
const icns = png2icons.createICNS(master, png2icons.BICUBIC, 0)
if (!ico || !icns) {
  console.error('Failed to create .ico/.icns - is the source image square and at least 512x512?')
  process.exit(1)
}
writeFileSync('build/icon.ico', ico)
writeFileSync('build/icon.icns', icns)

// The sign-in email shows the logo (served by the website) on a header in the icon's main colour.
// Main colour = the most common exact colour among the opaque pixels (a full-bleed icon has its background colour).
const { data, info } = await sharp(master).raw().toBuffer({ resolveWithObject: true })
const counts = new Map()
for (let i = 0; i < data.length; i += info.channels) {
  if (info.channels === 4 && data[i + 3] < 200) continue
  const key = (data[i] << 16) | (data[i + 1] << 8) | data[i + 2]
  counts.set(key, (counts.get(key) ?? 0) + 1)
}
const top = [...counts.entries()].sort((x, y) => y[1] - x[1])[0]?.[0] ?? 0x18181b
const dominant = { r: (top >> 16) & 255, g: (top >> 8) & 255, b: top & 255 }
const hex = (n) => n.toString(16).padStart(2, '0')
const color = `#${hex(dominant.r)}${hex(dominant.g)}${hex(dominant.b)}`
const luminance = (0.2126 * dominant.r + 0.7152 * dominant.g + 0.0722 * dominant.b) / 255

// Cut the empty margin off the icon, then add an even margin in the brand colour so the logo melts into the header.
const glyph = await sharp(master)
  .trim({ threshold: 20 })
  .resize(120, 120, { fit: 'contain', background: { ...dominant, alpha: 1 } })
  .toBuffer()
writeFileSync(
  '../web/public/email-logo.png',
  await sharp(glyph)
    .extend({ top: 36, bottom: 36, left: 36, right: 36, background: { ...dominant, alpha: 1 } })
    .flatten({ background: dominant })
    .png()
    .toBuffer()
)
writeFileSync(
  '../api/src/brand.ts',
  `// Generated by \`pnpm icons\` from the app icon. Do not edit by hand.
/** The main colour of the app icon, and a text colour that is readable on top of it. */
export const BRAND = { color: '${color}', onColor: '${luminance > 0.6 ? '#18181b' : '#ffffff'}' } as const
`
)

console.log(`Icons generated from ${source}:`)
console.log('  build/icon.png  build/icon.ico  build/icon.icns  resources/icon.png')
console.log(`  ../web/public/email-logo.png  ../api/src/brand.ts (${color})`)
